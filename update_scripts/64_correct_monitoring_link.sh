#!/bin/sh
# ============================================================================
# 64_correct. update_scripts/64_correct_monitoring_link.sh
# ----------------------------------------------------------------------------
# НАЗНАЧЕНИЕ:
#   Исправляет неправильное размещение ссылки "Мониторинг" после скрипта 64.
#   1. Откатывает изменения в App.jsx (убирает ссылку из корневого компонента)
#   2. Добавляет пункт "Мониторинг" в гамбургер-меню (HamburgerMenu.jsx)
#
# ЗАПУСК:
#   ./64_correct_monitoring_link.sh
# ============================================================================

set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT_ROOT=$(dirname "$SCRIPT_DIR")
FRONTEND_SRC="$PROJECT_ROOT/frontend/src"

echo "============================================================================"
echo "64_correct: Перемещение ссылки 'Мониторинг' в гамбургер-меню"
echo "Корень проекта: $PROJECT_ROOT"
echo "============================================================================"

# --- Проверяем наличие perl ---
if ! command -v perl >/dev/null 2>&1; then
    echo "ОШИБКА: не найден perl" >&2
    exit 1
fi

# ============================================================================
# ШАГ 1: Откат App.jsx к оригинальной версии
# ============================================================================
echo ""
echo "--- ШАГ 1: Откат App.jsx ---"

APP_FILE="$FRONTEND_SRC/App.jsx"
APP_BACKUP="$FRONTEND_SRC/App.jsx.bak-menu"

if [ ! -f "$APP_BACKUP" ]; then
    echo "  [WARN] Резервная копия $APP_BACKUP не найдена."
    echo "         Пропускаем откат App.jsx."
else
    cp "$APP_BACKUP" "$APP_FILE"
    echo "  [OK] App.jsx восстановлен из резервной копии"
fi

# ============================================================================
# ШАГ 2: Добавление пункта "Мониторинг" в HamburgerMenu.jsx
# ============================================================================
echo ""
echo "--- ШАГ 2: Добавление пункта в гамбургер-меню ---"

MENU_FILE="$FRONTEND_SRC/components/HamburgerMenu.jsx"

if [ ! -f "$MENU_FILE" ]; then
    echo "  [FAIL] Файл $MENU_FILE не найден" >&2
    exit 1
fi

# Проверяем, есть ли уже пункт "Мониторинг"
if grep -q "Мониторинг" "$MENU_FILE"; then
    echo "  [OK] Пункт 'Мониторинг' уже есть в меню. Ничего не делаем."
else
    # Создаём резервную копию
    cp "$MENU_FILE" "$MENU_FILE.bak-64correct"
    echo "  [BAK] Создана резервная копия: $MENU_FILE.bak-64correct"

    # Добавляем пункт "Мониторинг" в начало массива MENU_ITEMS
    # Ищем строку с первым пунктом меню и вставляем перед ней
    perl -0777 -pi -e '
        s/(const MENU_ITEMS = \[\\n\\s*\{)/$1  { path: "\/", label: "Мониторинг", icon: "📹", enabled: true },\\\n$1/s
    ' "$MENU_FILE"

    # Проверяем результат
    if grep -q "Мониторинг" "$MENU_FILE"; then
        echo "  [FIXED] Пункт 'Мониторинг' добавлен в начало меню"
    else
        echo "  [FAIL] Не удалось добавить пункт автоматически" >&2
        echo "         Исправьте вручную в $MENU_FILE:" >&2
        echo "         Добавьте в начало массива MENU_ITEMS:" >&2
        echo "         { path: '/', label: 'Мониторинг', icon: '📹', enabled: true }," >&2
        exit 1
    fi
fi

# ============================================================================
# ШАГ 3: Удаление лишних стилей (если были добавлены)
# ============================================================================
echo ""
echo "--- ШАГ 3: Очистка стилей ---"

CSS_FILE="$FRONTEND_SRC/styles.css"

if [ -f "$CSS_FILE" ]; then
    # Удаляем стили .monitoring-link, если они есть
    if grep -q "\.monitoring-link" "$CSS_FILE"; then
        cp "$CSS_FILE" "$CSS_FILE.bak-64correct"
        perl -0777 -pi -e 's/\.monitoring-link\s*\{[^}]+\}//gs' "$CSS_FILE"
        perl -0777 -pi -e 's/\.monitoring-link:hover\s*\{[^}]+\}//gs' "$CSS_FILE"
        echo "  [OK] Стили .monitoring-link удалены из $CSS_FILE"
    else
        echo "  [SKIP] Стили .monitoring-link не найдены"
    fi
else
    echo "  [WARN] Файл $CSS_FILE не найден"
fi

# ============================================================================
# ИТОГ
# ============================================================================
echo ""
echo "============================================================================"
echo "Готово!"
echo ""
echo "Изменения:"
echo "  1. App.jsx — восстановлен (ссылка убрана)"
echo "  2. HamburgerMenu.jsx — добавлен пункт 'Мониторинг' в меню"
echo "  3. styles.css — удалены лишние стили"
echo ""
echo "Следующий шаг: пересоберите фронтенд"
echo "  cd $PROJECT_ROOT/frontend"
echo "  npm run build"
echo "============================================================================"