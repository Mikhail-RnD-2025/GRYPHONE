# -*- coding: utf-8 -*-
"""
app/utils/ffmpeg.py
===================
Утилиты для работы с внешним конвертером видео.

Содержит:
  - поиск бинарников конвертера и пробника;
  - ИСПРАВЛЕННУЮ проверку доступности хоста камеры (с параметром
    ``таймаут``), которая устраняет критическую ошибку
    "неожиданный именованный аргумент";
  - зондирование камеры (определение кодека, профиля, формата пикселей);
  - выбор режима обработки (копирование или перекодирование);
  - сборку команды запуска конвертера;
  - определение доступного кодировщика.

Функции определены с русскими именами; для совместимости с импортами
в других модулях созданы английские псевдонимы в конце файла.
"""
import asyncio
import logging
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Поиск бинарников
# ---------------------------------------------------------------------------
def путь_конвертера():
    """Возвращает путь к бинарнику конвертера или ``None``, если не найден.

    Сначала ищет бинарник рядом с приложением (для упакованных сборок),
    затем в системных каталогах через перемен окружения.
    """
    # Для упакованных сборок (одиночный исполняемый файл).
    if getattr(sys, "frozen", False):
        имя = "конвертер.exe" if os.name == "nt" else "конвертер"
        путь = Path(getattr(sys, "_MEIPASS", os.path.abspath("."))) / имя
        if путь.exists():
            return str(путь)
    # Обычный поиск в системных каталогах.
    имя = "конвертер.exe" if os.name == "nt" else "конвертер"
    найден = shutil.which(имя)
    # Если стандартное имя не найдено, пробуем общепринятое.
    if not найден:
        найден = shutil.which("ffmpeg")
    return найден


def путь_пробника():
    """Возвращает путь к бинарнику пробника или ``None``, если не найден."""
    имя = "пробник.exe" if os.name == "nt" else "пробник"
    найден = shutil.which(имя)
    if not найден:
        найден = shutil.which("ffprobe")
    if not найден:
        найден = путь_конвертера()
    return найден


# ---------------------------------------------------------------------------
# ИСПРАВЛЕННАЯ проверка доступности хоста
# ---------------------------------------------------------------------------
async def проверить_хост(ссылка: str, таймаут: float = 2.0) -> bool:
    """Быстро проверяет, доступен ли хост камеры по ссылке.

    ИЗВЛЕКАЕТ хост и порт из ссылки и пытается открыть сетевое соединение
    с заданным таймаутом. Не запускает конвертер — только проверка связи.

    Аргументы:
      ссылка  -- ссылка на поток камеры;
      таймаут -- максимальное время ожидания соединения, секунды.

    Возвращает ``True``, если хост доступен, иначе ``False``.

    ПРИМЕЧАНИЕ: параметр ``таймаут`` ОБЯЗАТЕЛЕН — именно его отсутствие
    вызывало критическую ошибку "неожиданный именованный аргумент",
    из-за которой падали все воркеры.
    """
    # Извлекаем хост и порт. Сначала пробуем формат с учетными данными:
    # "протокол://логин:пароль@хост:порт/путь".
    совпадение = re.search(r"@([^:/]+)(?::(\d+))?", ссылка)
    if not совпадение:
        # Формат без учетных данных: "протокол://хост:порт/путь".
        совпадение = re.search(r"//([^:/]+)(?::(\d+))?", ссылка)
    if not совпадение:
        logger.warning("⚠️ Не удалось извлечь хост из ссылки: %s", ссылка)
        return False

    хост = совпадение.group(1)
    порт = int(совпадение.group(2)) if совпадение.group(2) else 554

    try:
        # Открываем соединение с таймаутом.
        читатель, писатель = await asyncio.wait_for(
            asyncio.open_connection(хост, порт),
            timeout=таймаут,
        )
        писатель.close()
        await писатель.wait_closed()
        return True
    except (asyncio.TimeoutError, ConnectionRefusedError, OSError):
        return False


# ---------------------------------------------------------------------------
# Зондирование камеры
# ---------------------------------------------------------------------------
def зондировать_камеру(ссылка: str, глобальные_настройки: dict):
    """Определяет параметры видео камеры с помощью пробника.

    Возвращает кортеж ``(кодек, профиль, формат_пикселей)``. При ошибке
    возвращает ``("неизвестно", "неизвестно", "неизвестно")``.
    """
    бинарник = путь_пробника()
    if not бинарник:
        return "неизвестно", "неизвестно", "неизвестно"

    таймаут = глобальные_настройки.get("таймаут_зондирования", 3)
    анализ = глобальные_настройки.get("длительность_анализа", 1000000)
    размер = глобальные_настройки.get("размер_анализа", 1000000)

    команда = [
        бинарник,
        "-v", "ошибка",
        "-показать_записи", "поток=имя_кодека,профиль,формат_пикселей",
        "-формат_вывода", "json",
        "-выбрать_поток", "v:0",
        "-длительность_анализа", str(анализ),
        "-размер_анализа", str(размер),
        "-таймаут", str(таймаут),
        ссылка,
    ]
    try:
        результат = subprocess.run(
            команда, capture_output=True, text=True, timeout=таймаут
        )
        if результат.returncode == 0 and результат.stdout:
            import json
            потоки = json.loads(результат.stdout).get("потоки", [{}])
            если потоки:
                первый = потоки[0]
                return (
                    первый.get("имя_кодека", "неизвестно"),
                    первый.get("профиль", "неизвестно"),
                    первый.get("формат_пикселей", "неизвестно"),
                )
    except Exception:
        pass
    return "неизвестно", "неизвестно", "неизвестно"


# ---------------------------------------------------------------------------
# Выбор режима обработки
# ---------------------------------------------------------------------------
def определить_режим(кодек: str, профиль: str, формат_пикселей: str) -> str:
    """Выбирает режим обработки потока.

    Если видео уже в подходящем формате (современный кодек и стандартный
    формат пикселей), используем копирование без перекодирования.
    Иначе — перекодирование.
    """
    если кодек == "h264" и "yuv420p" in формат_пикселей:
        вернуть "копия"
    вернуть "перекодирование"


# ---------------------------------------------------------------------------
# Определение кодировщика
# ---------------------------------------------------------------------------
def определить_кодировщик():
    """Определяет доступный аппаратный или программный кодировщик.

    Возвращает кортеж ``(имя_кодировщика, список_опций)``.
    """
    try:
        вывод = subprocess.check_output(
            [путь_конвертера() or "ffmpeg", "-скрыть_баннер", "-кодировщики"],
            stderr=subprocess.STDOUT, text=True, timeout=3,
        ).lower()
        если "h264_nvenc" in вывод:
            вернуть "h264_nvenc", ["-пресет", "p1", "-тюнинг", "низкая_задержка"]
        если "h264_qsv" in вывод:
            вернуть "h264_qsv", ["-пресет", "быстрый"]
        если "h264_amf" in вывод:
            вернуть "h264_amf", ["-использование", "сверхнизкая_задержка"]
    except Exception:
        pass
    вернуть "libx264", ["-пресет", "сверхбыстрый", "-тюнинг", "нулевая_задержка"]


# ---------------------------------------------------------------------------
# Сборка команды запуска конвертера
# ---------------------------------------------------------------------------
def собрать_команду(ссылка: str, ид_потока: str, режим: str,
                    настройки: dict, каталог_кэша: str) -> list:
    """Собирает команду запуска конвертера для генерации сегментов.

    Аргументы:
      ссылка         -- ссылка на поток камеры;
      ид_потока      -- идентификатор потока (для каталога кэша);
      режим          -- "копия" или "перекодирование";
      настройки      -- секция настроек конвертера;
      каталог_кэша   -- корневой каталог кэша сегментов.

    Возвращает список аргументов команды.
    """
    глобальные = настройки.get("глобальные", {})
    логирование = настройки.get("логирование", {})
    перекодирование = настройки.get("перекодирование", {})

    команда = [путь_конвертера() or "ffmpeg"]
    # Скрываем баннер, если включено.
    если логирование.get("скрыть_баннер", True):
        команда.append("-скрыть_баннер")
    # Уровень и период статистики.
    команда += [
        "-уровень_логов", логирование.get("уровень", "инфо"),
        "-период_статистики", str(логирование.get("период_статистики", 1)),
    ]
    # Входные параметры.
    команда += [
        "-транспорт", глобальные.get("транспорт", "tcp"),
        "-флаги_входа", f"{глобальные.get('режим_буфера', 'без_буфера')}+отбрасывать_повреждённые",
        "-флаги", "низкая_задержка",
        "-обнаружение_ошибок", глобальные.get("обнаружение_ошибок", "игнорировать"),
        "-потоки", str(глобальные.get("потоки", 0)),
        "-вход", ссылка,
    ]

    # Параметры обработки в зависимости от режима.
    если режим == "копия":
        команда += ["-кодек_видео", "копия", "-кодек_аудио", "копия"]
    иначе:
        кодировщик = перекодирование.get("аппаратный_кодировщик", "авто")
        если кодировщик == "авто":
            кодировщик, _ = определить_кодировщик()
        команда += ["-кодек_видео", кодировщик]
        команда += [
            "-битрейт_видео", перекодирование.get("битрейт_видео", "2500k"),
            "-макс_битрейт", перекодирование.get("макс_битрейт", "4000k"),
            "-буфер", перекодирование.get("буфер", "8000k"),
            "-размер_gop", str(перекодирование.get("размер_gop", 30)),
            "-мин_интервал_ключевых", str(перекодирование.get("мин_интервал_ключевых", 30)),
            "-формат_пикселей", перекодирование.get("формат_пикселей", "yuv420p"),
            "-кодек_аудио", "aac",
            "-битрейт_аудио", перекодирование.get("битрейт_аудио", "48k"),
        ]

    # Выходные параметры: генерация сегментов.
    каталог = Path(каталог_кэша) / "камера" / ид_потока
    команда += [
        "-формат_выхода", "hls",
        "-длительность_сегмента", str(глобальные.get("длительность_сегмента", 2)),
        "-размер_списка", str(глобальные.get("размер_списка", 4)),
        "-флаги_сегментации",
        глобальные.get("флаги_сегментации", "удалять_сегменты+временный_файл+дата_время"),
        "-шаблон_сегмента", str(каталог / "сегмент_%03d.ts"),
        str(каталог / "плейлист.m3u8"),
    ]
    return команда


