#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
============================================================================
112. update_scripts/112_half_gradient_header.py
----------------------------------------------------------------------------
НАЗНАЧЕНИЕ:
  Возвращает градиентную шапку с размытием (как было до патча 111),
  но уменьшает непрозрачность каждого слоя градиента в 2 раза.

ИЗМЕНЕНИЯ:
  • Фон: почти прозрачный (0.08) → градиент (0.5 → 0.4 → 0.2)
  • Восстанавливается backdrop-filter: blur(8px)
  • Тени для текста сохраняются (улучшают читаемость)

БЫЛО (до патча):   0.95 → 0.85 → 0.4  (тёмная шапка)
СТАНЕТ (после):    0.5  → 0.4  → 0.2  (полупрозрачная шапка)

ИДЕМПОТЕНТНОСТЬ: повторный запуск безопасен.
ЗАПУСК: python update_scripts/112_half_gradient_header.py
============================================================================
"""

import sys
import re
from pathlib import Path


def main():
    project_root = Path.cwd()
    header_css = project_root / "frontend/src/styles/header.css"
    backup_css = project_root / "frontend/src/styles/header.css.bak-112"

    print("=" * 76)
    print("112: Градиентная шапка с уменьшенной наполовину прозрачностью")
    print(f"Корень проекта: {project_root}")
    print("=" * 76)
    print()

    # ========================================================================
    # ШАГ 1: Проверка существования файла
    # ========================================================================
    print("--- ШАГ 1: Проверка файла ---")
    if not header_css.exists():
        print("  [ERROR] Файл header.css не найден")
        sys.exit(1)
    print(f"  [OK] Найден файл: {header_css}")
    print()

    # ========================================================================
    # ШАГ 2: Резервная копия
    # ========================================================================
    print("--- ШАГ 2: Резервная копия ---")
    backup_css.write_text(header_css.read_text(encoding="utf-8"), encoding="utf-8")
    print(f"  [BAK] {backup_css.name}")
    print()

    # ========================================================================
    # ШАГ 3: Чтение и анализ текущего состояния
    # ========================================================================
    print("--- ШАГ 3: Анализ текущего состояния ---")
    content = header_css.read_text(encoding="utf-8")

    # Проверяем, есть ли уже градиент с нужными значениями
    target_gradient = "rgba(11, 13, 16, 0.5) 0%"
    if target_gradient in content:
        print("  [OK] Градиент с уменьшенной прозрачностью уже применён")
        print("  Повторное применение не требуется")
        print()
        print("=" * 76)
        print("Ничего не изменено. Файл уже в целевом состоянии.")
        print("=" * 76)
        return

    print("  Текущее состояние фона шапки:")
    for line in content.split('\n'):
        stripped = line.strip()
        if stripped.startswith('background:') and 'header' not in stripped:
            print(f"    {stripped}")
    print()

    # ========================================================================
    # ШАГ 4: Замена фона на градиент с уменьшенной прозрачностью
    # ========================================================================
    print("--- ШАГ 4: Применение градиента (наполовину) ---")

    # Новый блок фона с градиентом и размытием
    new_background = """  background: linear-gradient(
    to bottom,
    rgba(11, 13, 16, 0.5) 0%,
    rgba(11, 13, 16, 0.4) 70%,
    rgba(11, 13, 16, 0.2) 100%
  );
  backdrop-filter: blur(8px);"""

    # Паттерн для поиска текущего фона (почти прозрачный из патча 111)
    # Ищем строку с background внутри блока .header
    pattern = re.compile(
        r'(\.header\s*\{[^}]*?)background:\s*rgba\(11,\s*13,\s*16,\s*0\.08\);',
        re.DOTALL
    )

    match = pattern.search(content)
    if match:
        # Заменяем почти прозрачный фон на градиент
        content = pattern.sub(
            lambda m: m.group(1) + new_background,
            content,
            count=1
        )
        print("  [FIXED] Почти прозрачный фон заменён на градиент")
    else:
        # Если почти прозрачного фона нет, ищем любой background в .header
        pattern_any = re.compile(
            r'(\.header\s*\{[^}]*?)background:[^;]+;',
            re.DOTALL
        )
        match_any = pattern_any.search(content)
        if match_any:
            content = pattern_any.sub(
                lambda m: m.group(1) + new_background,
                content,
                count=1
            )
            print("  [FIXED] Существующий фон заменён на градиент")
        else:
            print("  [WARN] Не удалось найти фон для замены")
            print("  Попробуйте восстановить файл из бэкапа и запустить снова")
            sys.exit(1)

    # Удаляем дубликат backdrop-filter, если он уже был
    content = re.sub(
        r'(backdrop-filter:\s*blur\(8px\);)\s*\n\s*backdrop-filter:\s*blur\(8px\);',
        r'\1',
        content
    )

    # ========================================================================
    # ШАГ 5: Проверка синтаксиса
    # ========================================================================
    print()
    print("--- ШАГ 5: Проверка синтаксиса ---")
    open_count = content.count('{')
    close_count = content.count('}')

    if open_count == close_count:
        print(f"  [OK] Скобки сбалансированы ({open_count}/{close_count})")
    else:
        print(f"  [FAIL] Скобки НЕ сбалансированы ({open_count}/{close_count})")
        print(f"  Восстановите из бэкапа: {backup_css.name}")
        sys.exit(1)
    print()

    # ========================================================================
    # ШАГ 6: Сохранение результата
    # ========================================================================
    print("--- ШАГ 6: Сохранение ---")
    header_css.write_text(content, encoding="utf-8")
    print("  [OK] header.css обновлён")
    print()
    print("  Применённый градиент:")
    print("    • Верх:   rgba(11, 13, 16, 0.5)  — 50% непрозрачности")
    print("    • Середина: rgba(11, 13, 16, 0.4) — 40% непрозрачности")
    print("    • Низ:    rgba(11, 13, 16, 0.2)  — 20% непрозрачности")
    print("    • Размытие: blur(8px)")
    print()

    # ========================================================================
    # ИТОГ
    # ========================================================================
    print("=" * 76)
    print("Готово! Градиентная шапка с уменьшенной наполовину прозрачностью.")
    print()
    print("Сравнение:")
    print("  Было (оригинал):  0.95 → 0.85 → 0.4  (тёмная)")
    print("  Стало (патч 112): 0.5  → 0.4  → 0.2  (полупрозрачная)")
    print()
    print("Пересоберите фронтенд:")
    print("  cd frontend && npm run build")
    print()
    print(f"Резервная копия: {backup_css.name}")
    print("=" * 76)


if __name__ == "__main__":
    main()