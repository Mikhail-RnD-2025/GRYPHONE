#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
============================================================================
114. update_scripts/114_menu_lighter_and_style.py
----------------------------------------------------------------------------
НАЗНАЧЕНИЕ:
  1. Делает панель меню светлее (ближе к прозрачности шапки)
  2. Заменяет синий цвет активного пункта на стальной из общей стилистики

ИЗМЕНЕНИЯ:
  • Градиент меню: 0.85→0.75→0.65 → 0.6→0.5→0.35 (ближе к шапке)
  • Активный пункт: синий → стальной (в стиле проекта)

СТИЛИСТИКА ПРОЕКТА:
  • Шапка: градиент 0.5 → 0.4 → 0.2
  • Меню:  градиент 0.6 → 0.5 → 0.35 (чуть плотнее для читаемости)
  • Активный пункт: стальной #475569 (используется в .btn:hover)

ИДЕМПОТЕНТНОСТЬ: повторный запуск безопасен.
ЗАПУСК: python update_scripts/114_menu_lighter_and_style.py
============================================================================
"""

import sys
from pathlib import Path


def main():
    project_root = Path.cwd()
    hamburger_css = project_root / "frontend/src/styles/hamburger.css"
    backup_css = project_root / "frontend/src/styles/hamburger.css.bak-114"

    print("=" * 76)
    print("114: Светлее панель меню + стальной цвет активного пункта")
    print(f"Корень проекта: {project_root}")
    print("=" * 76)
    print()

    # ========================================================================
    # ШАГ 1: Проверка существования файла
    # ========================================================================
    print("--- ШАГ 1: Проверка файла ---")
    if not hamburger_css.exists():
        print("  [ERROR] Файл hamburger.css не найден")
        sys.exit(1)
    print(f"  [OK] Найден файл: {hamburger_css}")
    print()

    # ========================================================================
    # ШАГ 2: Резервная копия
    # ========================================================================
    print("--- ШАГ 2: Резервная копия ---")
    backup_css.write_text(hamburger_css.read_text(encoding="utf-8"), encoding="utf-8")
    print(f"  [BAK] {backup_css.name}")
    print()

    # ========================================================================
    # ШАГ 3: Анализ текущего состояния
    # ========================================================================
    print("--- ШАГ 3: Анализ текущего состояния ---")
    content = hamburger_css.read_text(encoding="utf-8")

    # Проверяем, применён ли уже новый стиль
    if "rgba(11, 13, 16, 0.6) 0%" in content and "rgba(71, 85, 105, 0.6)" in content:
        print("  [OK] Стиль уже обновлён (светлый градиент + стальной активный)")
        print()
        print("=" * 76)
        print("Ничего не изменено. Файл уже в целевом состоянии.")
        print("=" * 76)
        return

    print("  Текущие значения градиента меню:")
    for line in content.split('\n'):
        stripped = line.strip()
        if 'rgba(11, 13, 16' in stripped:
            print(f"    {stripped}")
    print()

    # ========================================================================
    # ШАГ 4: Изменение градиента (светлее)
    # ========================================================================
    print("--- ШАГ 4: Осветление градиента меню ---")

    changes_made = []

    # Замена градиента на более светлый
    gradient_replacements = [
        ("rgba(11, 13, 16, 0.85) 0%", "rgba(11, 13, 16, 0.6) 0%"),
        ("rgba(11, 13, 16, 0.75) 70%", "rgba(11, 13, 16, 0.5) 70%"),
        ("rgba(11, 13, 16, 0.65) 100%", "rgba(11, 13, 16, 0.35) 100%"),
    ]

    for old, new in gradient_replacements:
        if old in content:
            content = content.replace(old, new)
            changes_made.append(f"Градиент: {old} → {new}")
        else:
            print(f"  [WARN] Не найдено: {old}")

    print(f"  [OK] Градиент осветлён")
    print()

    # ========================================================================
    # ШАГ 5: Замена цвета активного пункта
    # ========================================================================
    print("--- ШАГ 5: Стальной цвет активного пункта ---")

    # Синий → стальной (из общей стилистики проекта)
    active_replacements = [
        ("rgba(37, 99, 235, 0.6)", "rgba(71, 85, 105, 0.6)"),
        ("#2563eb", "#475569"),  # на случай, если где-то остался чистый синий
    ]

    for old, new in active_replacements:
        if old in content:
            content = content.replace(old, new)
            changes_made.append(f"Активный пункт: {old} → {new}")

    print("  [OK] Активный пункт теперь стальной (#475569)")
    print()

    # ========================================================================
    # ШАГ 6: Проверка синтаксиса
    # ========================================================================
    print("--- ШАГ 6: Проверка синтаксиса ---")
    open_count = content.count('{')
    close_count = content.count('}')

    if open_count == close_count:
        print(f"  [OK] Скобки сбалансированы ({open_count}/{close_count})")
    else:
        print(f"  [FAIL] Скобки НЕ сбалансированы ({open_count}/{close_count})")
        print(f"  Восстановите из бэкапа: {backup_css.name}")
        sys.exit(1)
    print()

    # ========================================================================
    # ШАГ 7: Сохранение результата
    # ========================================================================
    print("--- ШАГ 7: Сохранение ---")
    hamburger_css.write_text(content, encoding="utf-8")
    print("  [OK] hamburger.css обновлён")
    print()
    print("  Внесённые изменения:")
    for change in changes_made:
        print(f"    • {change}")
    print()

    # ========================================================================
    # ИТОГ
    # ========================================================================
    print("=" * 76)
    print("Готово! Панель меню светлее и в общей стилистике.")
    print()
    print("Новый стиль:")
    print("  • Шапка: градиент 0.5 → 0.4 → 0.2")
    print("  • Меню:  градиент 0.6 → 0.5 → 0.35 (близко к шапке)")
    print("  • Активный пункт: стальной #475569 (не синий)")
    print()
    print("Пересоберите фронтенд:")
    print("  cd frontend && npm run build")
    print()
    print(f"Резервная копия: {backup_css.name}")
    print("=" * 76)


if __name__ == "__main__":
    main()